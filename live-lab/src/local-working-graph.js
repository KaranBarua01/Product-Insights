/** Source-grounded working taxonomy graph constructed from completed laptop research.
 * No additional Cloudflare model call, no original taxonomy mutation and no OS writes.
 */
export const LOCAL_WORKING_GRAPH_SCHEMA='pi-local-working-taxonomy/v1';
const clean=(x,n=165)=>String(x??'').replace(/\s+/g,' ').trim().slice(0,n);
const norm=x=>clean(x).toLowerCase();
const cap=(v,n)=>Array.isArray(v)?v.slice(0,n):[];
/**
 * A category suggestion only counts as mapped when its code exists in the
 * installed full master. New working nodes remain separate from master nodes.
 */
export function buildLaptopWorkingGraph(facts,originalReference){
 const isInstalled=originalReference?.status==='installed'&&
   Array.isArray(originalReference.nodes)&&originalReference.nodes.length>0;
 const originals=new Map(isInstalled?originalReference.nodes.map(n=>[n.code,n]):[]);
 const records=cap(facts?.productIntelligence?.products,65),nodes=[],links=[],mappings=[];
 const seen=new Set(); let unresolved=0;
 for(const [index,p] of records.entries()){
   const name=clean(p?.name,135),sourceUrl=clean(p?.sourceUrl,500);
   if(!name||!sourceUrl)continue;
   const id='product:'+index;
   nodes.push({id,kind:'product',label:name,sourceUrl,status:'website_candidate'});
   let acceptedMappings=0;
   for(const suggestion of cap(p?.taxonomy?.suggestions,3)){
     const code=clean(suggestion.code,180),node=originals.get(code);
     if(!node)continue;
     mappings.push({product:name,sourceUrl,targetCode:node.code,targetLabel:node.label,
       originalPath:node.path,method:clean(suggestion.method||'candidate_unverified',100),
       status:'ai_or_deterministic_candidate_unverified'});
     links.push({from:id,to:'original:'+code,relation:'proposed_taxonomy_mapping',status:'needs_review'});
     acceptedMappings++;
   }
   if(!acceptedMappings)unresolved++;
   for(const [kind,entries,field,relation] of [
     ['part',p.components,'value','source_mentioned_component'],
     ['material',p.materials,'value','source_mentioned_material']]){
     for(const x of cap(entries,9)){
       const label=clean(x?.[field],120),quote=clean(x?.evidence?.quote,230);
       if(!label||!quote)continue;
       const unique=id+'|'+kind+'|'+norm(label);
       if(seen.has(unique))continue;seen.add(unique);
       const itemId='working:'+nodes.length;
       nodes.push({id:itemId,kind,label,sourceUrl:clean(x.evidence.sourceUrl,500),
         evidenceQuote:quote,sourceMethod:clean(x.origin||'website_or_local_ollama',90),
         status:'unverified_website_or_local_ai_candidate'});
       links.push({from:id,to:itemId,relation,status:'needs_review'});
     }
   }
 }
 const added=nodes.filter(n=>n.kind!=='product');
 return {schemaVersion:LOCAL_WORKING_GRAPH_SCHEMA,status:nodes.length?'candidate_graph':'no_products',
   mode:'read_only_original_plus_per_run_working_overlay',
   source:'local_laptop_investigation',
   model:clean(facts?.technical?.localOllama?.model||'not_reported',90),
   originalReference:{status:isInstalled?'installed':'not_loaded',
     nodeHash:isInstalled?originalReference.nodeHash:null,totalNodes:isInstalled?originalReference.totalNodes:0},
   nodes,links,mappings,unmappedProducts:unresolved,
   counts:{products:nodes.filter(n=>n.kind==='product').length,
     parts:added.filter(n=>n.kind==='part').length,
     materials:added.filter(n=>n.kind==='material').length,
     processCandidates:0,mappings:mappings.length},
   note:'Source-backed and AI suggestions are unverified. No inferred process requirements are generated by this graph.',
   originalMasterModified:false,osWritePerformed:false};
}
